-- file_key is nullable: a draft is created automatically when a meeting is held, before any document exists.
CREATE TABLE protocol (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id   BIGINT      NOT NULL UNIQUE REFERENCES meeting (id),
    org_id       BIGINT      NOT NULL REFERENCES organization (id),
    status       VARCHAR(16) NOT NULL,
    file_key     VARCHAR(255),
    file_name    VARCHAR(255),
    approved_at  TIMESTAMP WITH TIME ZONE,
    approved_by  BIGINT REFERENCES users (id),
    published_at TIMESTAMP WITH TIME ZONE,
    published_by BIGINT REFERENCES users (id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX protocol_org_idx ON protocol (org_id, status);
