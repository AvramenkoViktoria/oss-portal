CREATE TABLE organization (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(16)  NOT NULL UNIQUE,
    name       VARCHAR(255) NOT NULL,
    messenger  VARCHAR(16)  NOT NULL,
    channel_id VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- user_id references users, which is created by the authentication migration that adds the constraint.
CREATE TABLE membership (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    org_id     BIGINT       NOT NULL REFERENCES organization (id),
    faculty    VARCHAR(255) NOT NULL,
    position   VARCHAR(255) NOT NULL,
    term_start DATE         NOT NULL,
    term_end   DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT membership_term_order CHECK (term_end IS NULL OR term_end >= term_start)
);

CREATE INDEX membership_org_idx ON membership (org_id);
CREATE INDEX membership_user_idx ON membership (user_id);

