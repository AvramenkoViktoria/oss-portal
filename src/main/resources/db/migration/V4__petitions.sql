CREATE TABLE petition (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    text             TEXT         NOT NULL,
    author_id        BIGINT       NOT NULL REFERENCES users (id),
    org_id           BIGINT       NOT NULL REFERENCES organization (id),
    status           VARCHAR(16)  NOT NULL,
    link_type        VARCHAR(32),
    meeting_id       BIGINT REFERENCES meeting (id),
    rejection_reason VARCHAR(1024),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX petition_org_idx ON petition (org_id, created_at DESC);
CREATE INDEX petition_author_idx ON petition (author_id);
CREATE INDEX petition_meeting_idx ON petition (meeting_id);
