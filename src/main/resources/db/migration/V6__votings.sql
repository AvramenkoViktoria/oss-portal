CREATE TABLE voting (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocol_id    BIGINT  NOT NULL REFERENCES protocol (id),
    agenda_item_id BIGINT REFERENCES agenda_item (id),
    question       TEXT    NOT NULL,
    result         VARCHAR(16),
    votes_for      INT     NOT NULL DEFAULT 0,
    votes_against  INT     NOT NULL DEFAULT 0,
    votes_abstain  INT     NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX voting_protocol_idx ON voting (protocol_id);

CREATE TABLE vote_record (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voting_id     BIGINT      NOT NULL REFERENCES voting (id),
    membership_id BIGINT      NOT NULL REFERENCES membership (id),
    choice        VARCHAR(16) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    UNIQUE (voting_id, membership_id)
);
